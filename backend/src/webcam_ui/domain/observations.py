"""The small, typed subset of published E-SOH data retained by this application."""

import hashlib
import json
from dataclasses import asdict, dataclass
from datetime import datetime
from typing import Literal

Parameter = Literal["snow", "visibility"]
STANDARD_NAMES: dict[str, Parameter] = {
    "surface_snow_area_fraction": "snow",
    "visibility_in_air": "visibility",
}


def stable_id(*parts: object) -> str:
    return hashlib.sha256(json.dumps(parts, ensure_ascii=True, separators=(",", ":")).encode()).hexdigest()


@dataclass(frozen=True)
class StreamIdentity:
    naming_authority: str
    platform: str
    standard_name: str
    level: float
    function: str
    period: str
    instrument: str
    source_stream_id: str | None
    derived_suffix: str | None
    processing_suffix: str | None

    @property
    def observation_stream_id(self) -> str:
        return stable_id(self.naming_authority, self.platform, self.standard_name, self.level,
                         self.function, self.period, self.instrument)

    @property
    def derived_stream_id(self) -> str:
        return stable_id(self.naming_authority, self.platform,
                         self.source_stream_id or self.instrument, self.derived_suffix)

    @property
    def processing_stream_id(self) -> str:
        return stable_id(self.derived_stream_id, self.processing_suffix or self.instrument)


@dataclass(frozen=True)
class Observation:
    identity: StreamIdentity
    parameter: Parameter
    download_timestamp: datetime
    latitude: float
    longitude: float
    altitude: float | None
    country: str | None
    name: str
    platform_name: str | None
    unit: str
    provider_url: str | None
    provider_kind: str | None
    provider_webcam_id: str | None
    tags: tuple[str, ...]
    raw_lower: float | None
    raw_upper: float | None
    snow_class: int | None
    visibility_lower: float | None
    visibility_upper: float | None
    visibility_center: float | None
    acquisition_timestamp: datetime | None
    processing_timestamp: datetime | None
    provider_timestamp: datetime | None
    publication_timestamp: datetime | None
    model_version: str | None
    postprocessing_version: str | None
    image_access: str | None
    processing_level: str | None
    quality_code: int | None
    publication_id: str | None
    esoh_pubtime: datetime | None
    snow_qualification: int | None = None
    visibility_qualification: int | None = None
    snow_threshold_low: float | None = None
    snow_threshold_high: float | None = None

    @property
    def fingerprint(self) -> str:
        """Ignore transport IDs/times regenerated by E-SOH on a publisher retry."""
        content = asdict(self)
        content.pop("publication_id")
        content.pop("esoh_pubtime")
        # Preserve pre-migration fingerprints when the new optional metadata is absent.
        for field in ("snow_qualification", "visibility_qualification", "snow_threshold_low", "snow_threshold_high"):
            if content[field] is None or (field == "visibility_qualification" and content[field] == 2):
                content.pop(field)
        return hashlib.sha256(json.dumps(content, default=str, sort_keys=True,
                                         separators=(",", ":")).encode()).hexdigest()
